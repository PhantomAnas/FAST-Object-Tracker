_TEMPLATE = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="{fill}" '
             'stroke="{color}" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">{body}</svg>')

_cache: dict[tuple, QIcon] = {}
ICON_SIZE = QSize(17, 17)


def svg_bytes(name: str, color: str = "#e6e8ec", filled: bool = False) -> bytes:
    return _TEMPLATE.format(body=_SVG[name], color=color, fill=color if filled else "none").encode()


def pixmap(name: str, size: int = 18, color: str = "#e6e8ec", filled: bool = False, dpr: float = 1.0) -> QPixmap:
    renderer = QSvgRenderer(QByteArray(svg_bytes(name, color, filled)))
    px = int(size * dpr)
    img = QImage(px, px, QImage.Format.Format_ARGB32_Premultiplied)
    img.fill(Qt.GlobalColor.transparent)
    p = QPainter(img)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(p, QRectF(0, 0, px, px))
    p.end()
    pm = QPixmap.fromImage(img)
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name: str, color: str = "#e6e8ec", filled: bool = False) -> QIcon:
    key = (name, color, filled)
    if key not in _cache:
        ic = QIcon()
        for size in (16, 20, 24, 32):
            for dpr in (1.0, 2.0):
                ic.addPixmap(pixmap(name, size, color, filled, dpr))
        _cache[key] = ic
    return _cache[key]
